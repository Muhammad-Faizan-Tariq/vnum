import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { randomUUID } from "node:crypto";
import { ArrowLeft, Check, MessageSquareText, PhoneOff, ShieldAlert } from "lucide-react";
import { Badge, StatusBadge } from "@/components/ui/badge";
import { buttonVariants } from "@/components/ui/button";
import { Card, CardHeader, Notice, SimulatedTag } from "@/components/ui/primitives";
import { CreateOrderForm } from "@/components/customer/forms";
import { CheckoutSteps } from "@/components/customer/steps";
import { requireUser } from "@/server/auth/session";
import { db } from "@/server/db";
import { expireStaleOrders } from "@/server/orders/service";
import { getNumberProvider } from "@/server/numbers/provider";
import { formatE164, formatMoney } from "@/lib/utils";

export const metadata: Metadata = { title: "Number details" };

export default async function NumberDetailPage({ params }: PageProps<"/dashboard/numbers/[id]">) {
  const user = await requireUser("/dashboard/numbers");
  const { id } = await params;
  await expireStaleOrders();
  const number = await db.virtualNumber.findUnique({
    where: { id },
    include: { services: { include: { service: true } } },
  });
  if (!number || number.status === "DISABLED") notFound();
  const mine = await db.order.findFirst({
    where: { userId: user.id, numberId: id, status: { in: ["PENDING_PAYMENT", "PAID_SANDBOX", "PROCESSING", "COMPLETED"] } },
  });
  const provider = getNumberProvider(number.provider);
  const display = formatE164(number.e164);
  // New key per page render: a double-clicked form reuses it and the server returns the same order.
  const idempotencyKey = randomUUID();

  return (
    <div>
      <Link href="/dashboard/numbers" className="mb-4 inline-flex items-center gap-1.5 text-[13px] text-muted-foreground hover:text-foreground">
        <ArrowLeft className="size-3.5" aria-hidden /> All numbers
      </Link>
      <CheckoutSteps current={2} />

      <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_22rem]">
        <div className="space-y-6">
          <Card>
            <div className="flex flex-wrap items-start justify-between gap-3 p-5">
              <div>
                <p className="eyebrow">{number.countryName}{number.region ? ` · ${number.region}` : ""}</p>
                <h1 className="mt-1 font-mono text-2xl font-semibold tracking-tight sm:text-3xl" data-testid="number-heading">
                  {display}
                </h1>
                <p className="mt-1 font-mono text-xs text-muted-foreground">{number.e164}</p>
              </div>
              <StatusBadge status={number.status} />
            </div>
            <dl className="grid divide-y divide-border border-t border-border text-sm sm:grid-cols-2 sm:divide-x sm:divide-y-0">
              <div className="space-y-2 p-5">
                <dt className="eyebrow">Capabilities</dt>
                <dd>
                  <ul className="space-y-1.5">
                    <li className="flex items-center gap-2">
                      {number.smsInbound ? <Check className="size-4 text-success" aria-hidden /> : <PhoneOff className="size-4 text-muted-foreground" aria-hidden />}
                      Receive SMS (simulated)
                    </li>
                    <li className="flex items-center gap-2">
                      {number.voice ? <Check className="size-4 text-success" aria-hidden /> : <PhoneOff className="size-4 text-muted-foreground" aria-hidden />}
                      <span className={number.voice ? "" : "text-muted-foreground"}>Voice {number.voice ? "(flagged, not simulated)" : "not supported"}</span>
                    </li>
                  </ul>
                </dd>
              </div>
              <div className="space-y-2 p-5">
                <dt className="eyebrow">Supported services</dt>
                <dd className="flex flex-wrap gap-1.5">
                  {number.services.map((s) => (
                    <Badge key={s.serviceId}>{s.service.name}</Badge>
                  ))}
                </dd>
              </div>
            </dl>
          </Card>

          <Card>
            <CardHeader title="Source" description="Where this number comes from." action={<SimulatedTag />} />
            <div className="space-y-3 p-4 text-sm">
              <p>
                <span className="font-medium">{provider.label}</span>. This is test inventory held in VNum&apos;s own database.
                {provider.simulated
                  ? " It is not active on any real telecommunications network, and messages to it are generated by the in-app simulator."
                  : ""}
              </p>
              <p className="flex items-start gap-2 text-[13px] text-muted-foreground">
                <MessageSquareText className="mt-0.5 size-4 shrink-0" aria-hidden />
                After purchase you can receive simulated SMS on this number in your Inbox. VNum is receive-only.
              </p>
            </div>
          </Card>
        </div>

        <aside aria-label="Order summary">
          <Card className="lg:sticky lg:top-20">
            <CardHeader title="Order summary" />
            <div className="space-y-4 p-4">
              <dl className="space-y-2 text-sm">
                <div className="flex justify-between gap-4">
                  <dt className="text-muted-foreground">Number</dt>
                  <dd className="font-mono text-[13px]">{display}</dd>
                </div>
                <div className="flex justify-between gap-4">
                  <dt className="text-muted-foreground">Term</dt>
                  <dd>One-time (sandbox)</dd>
                </div>
                <div className="flex justify-between gap-4 border-t border-border pt-3 text-base font-semibold">
                  <dt>Total</dt>
                  <dd className="tabular" data-testid="order-total">{formatMoney(number.priceCents)}</dd>
                </div>
              </dl>

              {mine ? (
                <Notice tone="info" title={mine.status === "COMPLETED" ? "You own this number" : "You already have an order for this number"}>
                  <Link
                    href={mine.status === "PENDING_PAYMENT" ? `/dashboard/checkout/${mine.id}` : `/dashboard/orders/${mine.id}`}
                    className="font-medium text-accent underline"
                  >
                    {mine.status === "PENDING_PAYMENT" ? "Continue to payment" : "View order"}
                  </Link>
                </Notice>
              ) : number.status === "AVAILABLE" ? (
                <CreateOrderForm numberId={number.id} idempotencyKey={idempotencyKey} price={formatMoney(number.priceCents)} />
              ) : (
                <Notice tone="warning" title={number.status === "RESERVED" ? "Reserved by another customer" : "No longer available"}>
                  {number.status === "RESERVED"
                    ? "It will return to inventory if they don't pay in time."
                    : "This number has been sold."}{" "}
                  <Link href="/dashboard/numbers" className="font-medium text-accent underline">
                    Browse other numbers
                  </Link>
                </Notice>
              )}

              <p className="flex items-start gap-2 text-xs text-muted-foreground">
                <ShieldAlert className="mt-0.5 size-3.5 shrink-0" aria-hidden />
                Sandbox checkout. You&apos;ll pay with a simulated crypto method; no money moves.
              </p>
            </div>
          </Card>
          <Link href="/dashboard/numbers" className={buttonVariants({ variant: "ghost", size: "sm" }, "mt-2 w-full")}>
            Choose a different number
          </Link>
        </aside>
      </div>
    </div>
  );
}
