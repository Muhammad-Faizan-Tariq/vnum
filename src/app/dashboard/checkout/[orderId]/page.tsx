import type { Metadata } from "next";
import Link from "next/link";
import { notFound, redirect } from "next/navigation";
import { AlertTriangle, Clock } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardHeader, Notice, SimulatedTag } from "@/components/ui/primitives";
import { CopyField, Countdown, PaymentMethodForm, PaymentSimulator } from "@/components/customer/forms";
import { CheckoutSteps } from "@/components/customer/steps";
import { requireUser } from "@/server/auth/session";
import { getOrderDetail } from "@/server/customer/queries";
import { cancelOrderAction } from "@/app/dashboard/actions";
import { PAYMENT_METHODS } from "@/lib/payment-methods";
import { formatE164, formatMoney } from "@/lib/utils";

export const metadata: Metadata = { title: "Checkout" };

export default async function CheckoutPage({ params }: PageProps<"/dashboard/checkout/[orderId]">) {
  const user = await requireUser("/dashboard/orders");
  const { orderId } = await params;
  const detail = await getOrderDetail(user.id, orderId);
  if (!detail) notFound();
  const { order } = detail;
  if (order.status !== "PENDING_PAYMENT") redirect(`/dashboard/orders/${order.id}`);

  const pending = order.payments.find((p) => p.status === "PENDING");
  const lastFailed = !pending ? order.payments.find((p) => p.status === "FAILED") : undefined;
  const info = pending ? PAYMENT_METHODS[pending.method] : undefined;

  return (
    <div>
      <CheckoutSteps current={3} />
      <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_22rem]">
        <div className="space-y-6">
          <div>
            <h1 className="text-xl font-semibold tracking-tight sm:text-2xl">Pay for {formatE164(order.number.e164)}</h1>
            <p className="mt-1 flex flex-wrap items-center gap-x-2 text-sm text-muted-foreground">
              <Clock className="size-4" aria-hidden />
              Number held for <Countdown to={order.expiresAt.toISOString()} />
              <span aria-hidden>·</span>
              Order <span className="font-mono">{order.reference}</span>
            </p>
          </div>

          {lastFailed && (
            <Notice tone="danger" title="Your last payment attempt failed" role="status">
              {lastFailed.failureReason ?? "The provider reported a failure."} Your number is still held. Choose a method to try again.
            </Notice>
          )}

          {!pending ? (
            <Card>
              <CardHeader title="Choose how to pay" description="All options are simulated. No funds move and no addresses are real." action={<SimulatedTag />} />
              <div className="p-4">
                <PaymentMethodForm orderId={order.id} amountCents={order.amountCents} />
              </div>
            </Card>
          ) : (
            <>
              <Card data-testid="payment-panel">
                <CardHeader
                  title={`Send ${pending.cryptoAmount} ${pending.cryptoSymbol}`}
                  description={`${info?.network}. Waiting for confirmation.`}
                  action={<SimulatedTag />}
                />
                <div className="space-y-4 p-4">
                  <div className="space-y-1.5">
                    <p className="text-[13px] font-medium">Deposit address</p>
                    <CopyField value={pending.depositAddress} label="deposit address" />
                    <p className="text-xs text-muted-foreground">
                      This address is generated by the simulator and is invalid on every real network. Do not send funds to it.
                    </p>
                  </div>
                  <dl className="grid grid-cols-2 gap-4 text-sm sm:grid-cols-3">
                    <div>
                      <dt className="text-[13px] text-muted-foreground">Amount due</dt>
                      <dd className="font-mono tabular">{pending.cryptoAmount} {pending.cryptoSymbol}</dd>
                    </div>
                    <div>
                      <dt className="text-[13px] text-muted-foreground">Reference</dt>
                      <dd className="font-mono">{pending.reference}</dd>
                    </div>
                    <div>
                      <dt className="text-[13px] text-muted-foreground">Status</dt>
                      <dd className="font-medium text-warning" data-testid="payment-status">Awaiting payment</dd>
                    </div>
                  </dl>
                  <p className="text-xs text-muted-foreground">{info?.note}</p>
                </div>
              </Card>
              <PaymentSimulator paymentId={pending.id} />
              <Card>
                <CardHeader title="Use a different method" />
                <div className="p-4">
                  <PaymentMethodForm orderId={order.id} amountCents={order.amountCents} current={pending.method} />
                </div>
              </Card>
            </>
          )}
        </div>

        <aside aria-label="Order summary" className="space-y-3">
          <Card className="lg:sticky lg:top-20">
            <CardHeader title="Order summary" />
            <dl className="space-y-2 p-4 text-sm">
              <div className="flex justify-between gap-4">
                <dt className="text-muted-foreground">Number</dt>
                <dd className="font-mono text-[13px]">{formatE164(order.number.e164)}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-muted-foreground">Country</dt>
                <dd>{order.number.countryName}</dd>
              </div>
              <div className="flex justify-between gap-4 border-t border-border pt-3 text-base font-semibold">
                <dt>Total</dt>
                <dd className="tabular">{formatMoney(order.amountCents)}</dd>
              </div>
            </dl>
            <div className="border-t border-border p-4">
              <form action={cancelOrderAction}>
                <input type="hidden" name="orderId" value={order.id} />
                <Button type="submit" variant="ghost" size="sm" className="w-full text-muted-foreground">
                  Cancel order and release number
                </Button>
              </form>
            </div>
          </Card>
          <p className="flex items-start gap-2 px-1 text-xs text-muted-foreground">
            <AlertTriangle className="mt-0.5 size-3.5 shrink-0" aria-hidden />
            Sandbox checkout only. If the timer runs out the order is cancelled and the number returns to inventory.{" "}
            <Link href="/dashboard/orders" className="underline">
              My orders
            </Link>
          </p>
        </aside>
      </div>
    </div>
  );
}
